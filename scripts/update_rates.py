#!/usr/bin/env python3
"""Refresh data/rates.js with today's exchange rates (local currency per one US dollar).

    python3 scripts/update_rates.py

The site also fetches fresh rates in the visitor's browser when it can, so this file is the
fallback it starts from. Run it daily (the GitHub Actions workflow does) to keep that fallback current.
Source: the free, keyless currency API by Fawaz Ahmed (https://github.com/fawazahmed0/exchange-api).
"""
import json
import os
import sys

from common import DATA_DIR, http_get, log, read_js, sig, write_js
from countries import COUNTRIES

RATE_URLS = [u for u in os.environ.get("GIL_RATES_URL", "").split(",") if u] or [
    "https://cdn.jsdelivr.net/npm/@fawazahmed0/currency-api@latest/v1/currencies/usd.min.json",
    "https://latest.currency-api.pages.dev/v1/currencies/usd.min.json",
]


def parse_rates(raw):
    """Turn the API's {"date": ..., "usd": {"inr": 88.1, ...}} into {"date", "rates": {"INR": 88.1}}."""
    table = raw.get("usd")
    if not isinstance(table, dict) or not raw.get("date"):
        raise ValueError("unexpected response shape (expected keys 'date' and 'usd')")
    rates = {}
    for code, value in table.items():
        if isinstance(value, (int, float)) and value > 0:
            rates[code.upper()] = float(value)
    rates["USD"] = 1.0
    return {"date": str(raw["date"]), "rates": rates}


def fetch_rates():
    errors = []
    for url in RATE_URLS:
        try:
            return parse_rates(json.loads(http_get(url, timeout=60)))
        except Exception as err:
            errors.append(f"{url}: {err}")
    raise RuntimeError("No exchange-rate source answered:\n  " + "\n  ".join(errors))


def write_rates(all_rates):
    needed = sorted({currency for _, _, currency in COUNTRIES.values()})
    rates = {code: sig(all_rates["rates"][code], 7) for code in needed if code in all_rates["rates"]}
    missing = [code for code in needed if code not in rates]
    previous = read_js(DATA_DIR / "rates.js")
    write_js(DATA_DIR / "rates.js", "GIL_RATES", {
        "date": all_rates["date"],
        "base": "USD",
        "source": "fawazahmed0/exchange-api",
        "rates": rates,
    }, "Generated by scripts/update_rates.py. Local currency per one US dollar.")
    log(f"Exchange rates for {all_rates['date']}: {len(rates)} currencies written to data/rates.js")
    if missing:
        log("  no rate published for: " + ", ".join(missing))
    if previous:
        jumps = []
        for code, value in rates.items():
            old = previous.get("rates", {}).get(code)
            if old and abs(value / old - 1) > 0.25:
                jumps.append(f"{code} {old:g} -> {value:g}")
        if jumps:
            log("  moved more than 25% since the last file (worth a look): " + "; ".join(jumps))
    return rates


def main():
    write_rates(fetch_rates())


if __name__ == "__main__":
    try:
        main()
    except Exception as err:
        log(f"\nExchange rates were NOT updated: {err}")
        sys.exit(1)
